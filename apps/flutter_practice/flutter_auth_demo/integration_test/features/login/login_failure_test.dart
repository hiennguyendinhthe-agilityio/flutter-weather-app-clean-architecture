import 'package:flutter/material.dart';
import 'package:flutter_auth_demo/core/di/injection.dart';
import 'package:flutter_auth_demo/main.dart' as app;
import 'package:flutter_test/flutter_test.dart';
import 'package:patrol/patrol.dart';

void main() {
  setUpAll(() async {
    await configureDependencies();
  });

  group('Login Failure Scenarios', () {
    patrolTest(
      'shows an error message on invalid credentials and stays on login page',
      ($) async {
        // 1. Arrange: Pump the app and wait for it to settle.
        // Dependency configuration is handled in `setUpAll`.
        await $.pumpWidgetAndSettle(const app.MyApp());

        // 2. Arrange: Verify initial state.
        await $(#loginPage).waitUntilVisible();
        expect($(const Key('errorMessage')), findsNothing);

        // 3. Act: Enter incorrect credentials and tap the sign-in button.
        await $(#emailField).enterText('test@example.com');
        await $(#passwordField).enterText('wrongpassword');
        await $(#signInButton).tap();

        // 4. Act: Wait for the UI to update after the failed login attempt.
        await $.pumpAndSettle();

        // 5. Assert: The error message text should be visible inside the correct container.
        // First, find the Text widget with the specific error message and wait for it to appear.
        final textFinder = find.text('Email and password are incorrect.');
        await $(textFinder).waitUntilVisible();

        // Next, find the ErrorMessage widget by its key.
        final errorMessageContainerFinder = find.byKey(
          const Key('errorMessage'),
        );

        // Now, verify the hierarchy: check that the found Text widget has an
        // ancestor that is the ErrorMessage widget. This is a very robust check.
        final ancestorFinder = find.ancestor(
          of: textFinder,
          matching: errorMessageContainerFinder,
        );

        // We expect to find exactly one such ancestor.
        expect(
          ancestorFinder,
          findsOneWidget,
          reason:
              'The error text should be a descendant of the ErrorMessage widget.',
        );

        // 6. Assert: Verify no navigation occurred.
        expect($(#loginPage).visible, isTrue);
        expect($(#signInButton).visible, isTrue);
      },
    );

    patrolTest('shows a validation error if the password is empty', ($) async {
      // 1. ARRANGE: Pump the app and ensure the login page is visible.
      await $.pumpWidgetAndSettle(const app.MyApp());
      await $(#loginPage).waitUntilVisible();

      // 2. ACT: Enter a valid email, leave the password empty, and tap sign-in.
      // This action triggers the Form's validation logic.
      await $(#emailField).enterText('test@example.com');
      await $(#signInButton).tap();

      // 3. PUMP & SETTLE: Wait for the UI to fully settle after the tap.
      // While a single `$.pump()` is often enough for synchronous validation,
      // using `pumpAndSettle()` provides extra stability by waiting for any
      // potential microtasks or brief animations to complete, preventing flakiness.
      await $.pumpAndSettle();

      // 4. ASSERT: Check for the client-side validation error message.
      // This error text is generated by the TextFormField's own validator.
      await $('Password is required').waitUntilVisible();

      // 5. ASSERT: Crucially, verify that the provider-level error message
      // widget (which indicates a server/API error) is NOT visible.
      // This confirms that the validation prevented a network request.
      expect($(const Key('errorMessage')), findsNothing);

      // 6. ASSERT: Verify that the app remains on the login page.
      expect($(#loginPage).visible, isTrue);
    });
  });
}
